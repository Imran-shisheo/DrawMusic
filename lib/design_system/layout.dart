/// Shared layout scale for application chrome. Document coordinates stay separate.
abstract final class CreativeSpace {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double page = 20;
  static const double section = 24;
  static const double xl = 32;
}

abstract final class CreativeRadius {
  static const double control = 16;
  static const double card = 24;
  static const double panel = 28;
}

abstract final class CreativeSize {
  static const double touchTarget = 48;
}
